/** JS 전처리가 파이썬(app.py의 MNIST형식으로_변환)과 픽셀 단위로 같은지 확인한다. */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MNIST형식으로_변환, 파이썬반올림, 경계상자, 잡음_제거 } from '../js/preprocess.js';
import { 기준값_읽기, 큰_그림_만들기, 사각형_그림_만들기 } from './helpers.js';

const { 기대값, 원본들, 전처리들 } = 기준값_읽기();

test('파이썬반올림은 .5를 짝수 쪽으로 반올림한다', () => {
  const 경우들 = [[0.5, 0], [1.5, 2], [2.5, 2], [3.5, 4], [-0.5, 0], [-1.5, -2], [2.4, 2], [2.6, 3], [-2.6, -3]];
  for (const [입력, 기대] of 경우들) assert.equal(파이썬반올림(입력), 기대, `입력 ${입력}`);
});

test('경계상자는 0이 아닌 픽셀을 감싸고 오른쪽·아래는 포함하지 않는다', () => {
  const 그림 = new Uint8Array(5 * 4); // 너비 5, 높이 4
  그림[1 * 5 + 1] = 10;
  그림[2 * 5 + 3] = 255;
  assert.deepEqual(경계상자(그림, 5, 4), [1, 1, 4, 3]);
  assert.equal(경계상자(new Uint8Array(20), 5, 4), null);
});

test('아무것도 그리지 않으면 null을 돌려준다', () => {
  assert.equal(MNIST형식으로_변환(new Uint8Array(280 * 280), 280, 280), null);
});

test('입력 길이가 너비×높이와 다르면 RangeError를 낸다', () => {
  assert.throws(() => MNIST형식으로_변환(new Uint8Array(10), 280, 280), RangeError);
});

test('MNIST 500장의 99% 이상이 파이썬 전처리와 픽셀 단위로 완전히 같다', () => {
  const 다른번호들 = [];
  for (let i = 0; i < 기대값.개수; i++) {
    const 결과 = MNIST형식으로_변환(큰_그림_만들기(원본들, i, 기대값.배치[i]), 280, 280);
    const 기대 = 전처리들.subarray(i * 784, (i + 1) * 784);
    if (!결과.every((값, j) => 값 === 기대[j])) 다른번호들.push(i);
  }
  const 같은수 = 기대값.개수 - 다른번호들.length;
  assert.ok(같은수 >= 기대값.개수 * 0.99, `같은 것 ${같은수}/${기대값.개수}, 다른 번호: ${다른번호들.slice(0, 10)}`);
});

test('잡음_제거는 기준 미만인 값만 0으로 만들고 입력을 바꾸지 않는다', () => {
  const 입력 = new Uint8Array([0, 1, 15, 16, 17, 255, 8]);
  const 원본복사 = Uint8Array.from(입력);
  const 결과 = 잡음_제거(입력, 16);
  assert.deepEqual(Array.from(결과), [0, 0, 0, 16, 17, 255, 0]);
  assert.deepEqual(Array.from(입력), Array.from(원본복사), '입력 배열을 바꾸면 안 된다');
  assert.notEqual(결과, 입력, '새 배열을 돌려줘야 한다');
});

test('잡음_제거는 기준을 생략하면 16을 쓴다', () => {
  const 결과 = 잡음_제거(new Uint8Array([15, 16]));
  assert.deepEqual(Array.from(결과), [0, 16]);
});

// 주의: "MNIST 500장의 99%..." 테스트와 달리, 여기서는 잡음_제거(기준=16)를 거친 결과를
// preprocessed.bin(파이썬이 잡음 없는 입력을 그대로 전처리한 값)과 픽셀 단위로 비교하지 않는다.
// 실제 MNIST 원본 이미지 자체가 경계 부분에 0~15 사이의 옅은 회색 값(안티앨리어싱)을 폭넓게 담고 있어서,
// 잡음_제거는 (주입한 잡음이 전혀 없어도) 그 값을 지워 Lanczos 축소 결과를 눈에 띄게 바꾼다
// (직접 측정: 잡음 없이 잡음_제거만 적용해도 앞 50장 중 48장이 preprocessed.bin과 한 픽셀이라도 달라짐).
// 반면 실제 원인인 "경계상자 폭주"는 아래에서 그대로 재현·검증할 수 있다.
test('캔버스 잡음이 섞이면 경계상자가 캔버스 전체로 커지고, 잡음_제거를 거치면 원래 경계상자로 돌아온다', () => {
  const 표본수 = Math.min(50, 기대값.개수);
  const 확장안됨 = [];
  const 복원안됨 = [];
  for (let i = 0; i < 표본수; i++) {
    const 큰그림 = 큰_그림_만들기(원본들, i, 기대값.배치[i]);
    const 잡음섞인그림 = Uint8Array.from(큰그림);
    for (let j = 0; j < 잡음섞인그림.length; j++) {
      if ((j * 7919 + i) % 1000 === 0) 잡음섞인그림[j] = Math.min(255, 잡음섞인그림[j] + 1);
    }
    const 원래경계 = 경계상자(큰그림, 280, 280);

    // 잡음_제거 없이 그대로 재면(문제 재현): 경계상자가 캔버스(280x280) 전체 가까이로 커진다.
    const 잡음경계 = 경계상자(잡음섞인그림, 280, 280);
    if (!(잡음경계[2] - 잡음경계[0] > 230 && 잡음경계[3] - 잡음경계[1] > 230)) 확장안됨.push(i);

    // 잡음_제거를 거치면(수정 확인): 경계상자가 원래(잡음 없는) 경계상자와 거의 같아진다.
    const 정제경계 = 경계상자(잡음_제거(잡음섞인그림), 280, 280);
    const 최대차 = Math.max(
      Math.abs(정제경계[0] - 원래경계[0]), Math.abs(정제경계[1] - 원래경계[1]),
      Math.abs(정제경계[2] - 원래경계[2]), Math.abs(정제경계[3] - 원래경계[3]),
    );
    if (최대차 > 15) 복원안됨.push([i, 최대차]);
  }
  assert.deepEqual(확장안됨, [], `잡음만으로는 경계상자가 캔버스 전체로 커지지 않은 번호(테스트 전제가 깨짐): ${확장안됨}`);
  assert.deepEqual(복원안됨, [], `잡음_제거 후에도 경계상자가 크게(15px 초과) 달라진 [번호, 차이]: ${JSON.stringify(복원안됨)}`);
});

for (const [이름, { 사각형, 출력 }] of Object.entries(기대값.특수경우)) {
  test(`극단적인 입력 '${이름}'도 파이썬 전처리와 완전히 같다`, () => {
    const 결과 = MNIST형식으로_변환(사각형_그림_만들기(사각형), 280, 280);
    assert.deepEqual(Array.from(결과), 출력);
  });
}
